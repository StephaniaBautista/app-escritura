export function getMapIcon(id: string): MapIconDef | undefined {
  return MAP_ICONS.find((icon) => icon.id === id)
}

export function iconsByCategory(category: MapIconCategory): MapIconDef[] {
  return MAP_ICONS.filter((icon) => icon.category === category)
}

export function mapIconSvg(icon: MapIconDef, color: string): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${MAP_ICON_SIZE} ${MAP_ICON_SIZE}"><path d="${icon.path}" fill="${color}"/></svg>`
}
