import { chromium } from '@playwright/test'

const browser = await chromium.launch()
const page = await browser.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
await page.goto('http://localhost:5173/login')
await page.fill('input[name="email"]', 'test@archivum.app')
await page.fill('input[name="password"]', 'Test1234!')
await page.click('button[type="submit"]')
await page.waitForURL('**/app')
await page.goto('http://localhost:5173/app/admin')
await page.getByRole('button', { name: 'Estructura' }).click()
await page.getByRole('button', { name: 'Nueva pregunta' }).click()
await page.getByLabel('Texto (es)').fill('¿Pregunta de prueba?')
await page.getByRole('button', { name: 'Crear pregunta' }).click()
await page.waitForTimeout(1500)
console.log('PAGE_ERRORS:', errors.join(' | ') || '(none)')
console.log('BUTTONS:', JSON.stringify(await page.evaluate(() => Array.from(document.querySelectorAll('button')).map((b) => b.innerText).filter((t) => t.trim()))))
const editButtons = await page.evaluate(() => Array.from(document.querySelectorAll('button[aria-label]')).map((b) => b.getAttribute('aria-label')).filter((l) => l && l.includes('Editar')))
console.log('EDIT_LABELS:', JSON.stringify(editButtons))
await page.locator('button[aria-label="Editar pregunta"]').last().click()
await page.waitForTimeout(800)
console.log('AFTER_EDIT_BUTTONS:', JSON.stringify(await page.evaluate(() => Array.from(document.querySelectorAll('button')).map((b) => b.innerText).filter((t) => t.trim()))))
await browser.close()
